  "  const version = taskFormDraftVersion(form);",
  "  if (version !== null) draft.version = version;",
  "  try {",
  "    localStorage.setItem(key, JSON.stringify(draft));",
  "  } catch (e) {}",
  "}",
  "function scheduleTaskFormDraft(form) {",
  "  if (form._taskDraftTimer) clearTimeout(form._taskDraftTimer);",
  "  form._taskDraftTimer = setTimeout(function () { saveTaskFormDraft(form); }, 500);",
  "}",
